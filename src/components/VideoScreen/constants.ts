/**
 * 補正しない誤差（秒）
 *
 * この範囲なら合っているとみなす。狭くすると補正が止まらなくなる。
 * 共有時計の実効精度（Quest で 18ms 程度）よりはるかに大きく取ってあるのは、
 * ブラウザが `video.currentTime` の設定を要求位置ぴったりに着地させないため。
 */
export const SYNC_DEAD_BAND = 0.3

/**
 * 再生速度で吸収する誤差の上限（秒）
 *
 * これを超える誤差は速度調整では現実的な時間で吸収できないのでシークを検討する。
 */
export const SYNC_RATE_LIMIT = 5

/**
 * 再生速度の補正幅（±5%）
 *
 * 大きくすると音程の変化が耳につく。5% なら 1 秒の遅れを 20 秒で吸収できる。
 */
export const SYNC_RATE_ADJUSTMENT = 0.05

/**
 * シーク先がバッファ内かを判定するときの余裕（秒）
 *
 * バッファの端ぎりぎりへシークすると、着地した直後に再生が止まる。
 */
export const SYNC_BUFFER_MARGIN = 1
